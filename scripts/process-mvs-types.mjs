import fs from 'node:fs';

const rawPath = './src/utils/.mvs-types-raw.d.ts';

// Read molstar version from deno.json import map
const denoConfig = JSON.parse(fs.readFileSync('./deno.json', 'utf-8'));
const molstarEntry = Object.values(denoConfig.imports).find((v) =>
  v.startsWith('npm:molstar@')
);
if (!molstarEntry) throw new Error('molstar version not found in deno.json imports');
const molstarVersion = molstarEntry.match(/npm:molstar@([^/]+)/)[1];

let data = fs.readFileSync(rawPath, 'utf-8');
data = data
  .replaceAll('`', '\\`')
  .replaceAll('${', '\\${')
  .replaceAll(/(\r\n|\n|\r)/g, '\n');

const lib = ['Vec3', 'Mat3', 'Mat4', 'Quat', 'Euler'];

const lines = data.split('\n');
const final = [
  '// Automatically generated file. Do not edit manually.',
  `// This file is generated by deno task mvs-types (molstar@${molstarVersion})`,
  '',
  '/**',
  ' * TypeScript type definitions for the Mol* Viewer (MVS) API.',
  ' * ',
  ' * This string contains complete type definitions that can be used with Monaco Editor',
  ' * to provide IntelliSense/autocomplete for MVS scene JavaScript code.',
  ' * ',
  ' * @example',
  ' * ```typescript',
  ' * import { setupMonacoCodeCompletion, MVSTypes } from "@molstar/molstar-components";',
  ' * ',
  ' * // Configure Monaco Editor for MVS code completion',
  ' * setupMonacoCodeCompletion(monaco, MVSTypes);',
  ' * ```',
  ' */',
  'export const MVSTypes: string = `',
  'namespace _ {',
  ...lines.map((line) => `    ${line}`),
  '}',
  '',
  'declare const builder: _.Builder;',
  ...lib.map((name) => `declare const ${name}: typeof _.${name};`),
  `declare function decodeColor(input: string): number;`,
  '`;',
];

fs.writeFileSync('./src/utils/mvs-types.ts', final.join('\n'), 'utf-8');
fs.rmSync(rawPath);

console.log(`Generated src/utils/mvs-types.ts from molstar@${molstarVersion}`);
